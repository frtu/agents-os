#!/usr/bin/env python3
"""
pdf_lib — low-level, reusable building blocks for turning a PDF into Markdown.

Every function here does ONE thing and holds no loop over files and no CLI
logic. The orchestrator (`pdf_to_md.py`) decides what to call and when.
Other skills may import these functions directly:

    import sys; sys.path.insert(0, "<skills-dir>/transcribe-pdf/scripts")
    from pdf_lib import open_pdf, extract_page_best, render_markdown

Groups:
  - paths & files ....... target_md_path, file_sha256, write_text_atomic,
                          read_frontmatter, is_generated_by_us, is_up_to_date
  - opening ............. open_pdf, PdfLockedError
  - metadata ............ pdf_metadata
  - text extraction ..... extract_page_text, extract_page_best, count_chars,
                          has_enough_text, clean_text
  - OCR ................. ocr_backend, ocr_pages
  - rendering ........... PageResult, load_template, fill, render_markdown
"""

from __future__ import annotations

import datetime as _dt
import hashlib
import json
import os
import platform
import re
import shutil
import subprocess
import tempfile
from dataclasses import dataclass, field
from pathlib import Path
from typing import Iterable

GENERATOR = "transcribe-pdf"
LEGACY_GENERATORS = ("pdf-extract",)   # former skill name: its .md files are still ours
GENERATOR_VERSION = "1.1.0"   # keep equal to `version` in ../SKILL.md (tested)
SCRIPTS_DIR = Path(__file__).resolve().parent
DEFAULT_TEMPLATE = SCRIPTS_DIR.parent / "references" / "templates" / "markdown-output.md"
CACHE_DIR = Path(os.environ.get("TRANSCRIBE_PDF_CACHE", Path.home() / ".cache" / "transcribe-pdf"))


# --------------------------------------------------------------------------- #
# Paths & files
# --------------------------------------------------------------------------- #

def target_md_path(pdf_path: Path, suffix: str = ".md") -> Path:
    """Return the Markdown path next to the PDF: `a/b/Report.pdf` -> `a/b/Report.md`."""
    pdf_path = Path(pdf_path)
    return pdf_path.with_name(pdf_path.stem + suffix)


def file_sha256(path: Path, chunk: int = 1 << 16) -> str:
    """SHA-256 hex digest of a file, streamed."""
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for block in iter(lambda: f.read(chunk), b""):
            h.update(block)
    return h.hexdigest()


def write_text_atomic(path: Path, text: str) -> None:
    """Write UTF-8 text via a temp file + rename, so a crash never leaves half a file."""
    path = Path(path)
    fd, tmp = tempfile.mkstemp(prefix=".transcribe-pdf-", suffix=".tmp", dir=path.parent)
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        os.replace(tmp, path)
    except BaseException:
        if os.path.exists(tmp):
            os.unlink(tmp)
        raise


_FM_RE = re.compile(r"\A---\n(.*?)\n---\n", re.S)


def read_frontmatter(md_path: Path) -> dict[str, str]:
    """Parse the flat `key: value` YAML frontmatter of a Markdown file ({} if none)."""
    try:
        head = Path(md_path).read_text(encoding="utf-8", errors="replace")[:4096]
    except FileNotFoundError:
        return {}
    m = _FM_RE.match(head)
    if not m:
        return {}
    out: dict[str, str] = {}
    for line in m.group(1).splitlines():
        if ":" in line and not line.startswith((" ", "-")):
            k, v = line.split(":", 1)
            out[k.strip()] = v.strip().strip('"')
    return out


def is_generated_by_us(md_path: Path) -> bool:
    """True if the Markdown file exists and was written by this tool."""
    return read_frontmatter(md_path).get("generator") in (GENERATOR, *LEGACY_GENERATORS)


def is_up_to_date(pdf_path: Path, md_path: Path, pdf_sha: str | None = None) -> bool:
    """True if `md_path` was generated by us from exactly this PDF content."""
    fm = read_frontmatter(md_path)
    if fm.get("generator") not in (GENERATOR, *LEGACY_GENERATORS):
        return False
    return fm.get("source_sha256") == (pdf_sha or file_sha256(pdf_path))


# --------------------------------------------------------------------------- #
# Opening
# --------------------------------------------------------------------------- #

class PdfLockedError(Exception):
    """The PDF is encrypted and none of the passwords tried opened it."""


def open_pdf(pdf_path: Path, passwords: Iterable[str] = ()):
    """
    Open a PDF with pypdf. If encrypted, try the empty password (owner-only
    protection) then each given password. Raises PdfLockedError if all fail.
    """
    from pypdf import PdfReader  # imported lazily so the module loads without deps

    reader = PdfReader(str(pdf_path))
    if reader.is_encrypted:
        for pwd in ["", *passwords]:
            try:
                if reader.decrypt(pwd):
                    return reader
            except Exception as exc:  # e.g. missing AES provider
                if "cryptography" in str(exc) or "AES" in str(exc):
                    raise RuntimeError(
                        "AES-encrypted PDF: install `pycryptodome` (see scripts/requirements.txt)"
                    ) from exc
        raise PdfLockedError(f"password required: {pdf_path}")
    return reader


