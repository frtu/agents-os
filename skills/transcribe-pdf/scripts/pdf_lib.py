def extract_page_text(page, mode: str = "layout") -> str:
    """
    Extract one page's text with pypdf.
      mode="layout": keeps column alignment (best for tables, invoices, forms);
                     may return nothing for text nested in Form XObjects.
      mode="plain":  reading-order text; descends into Form XObjects.
    Never raises: returns "" on failure.
    """
    try:
        if mode == "layout":
            return page.extract_text(extraction_mode="layout") or ""
        return page.extract_text() or ""
    except Exception:
        return ""


def count_chars(text: str) -> int:
    """Number of non-whitespace characters."""
    return sum(1 for c in text if not c.isspace())


def has_enough_text(text: str, min_chars: int = 20) -> bool:
    """True if the text holds at least `min_chars` non-whitespace characters."""
    return count_chars(text) >= min_chars


def extract_page_best(page, prefer: str = "layout", ratio: float = 0.9) -> tuple[str, str]:
    """
    Try both pypdf modes and keep the better one. Returns (text, method).
    `prefer` wins unless it captured fewer than `ratio` x the other mode's characters.
    """
    other = "plain" if prefer == "layout" else "layout"
    a = extract_page_text(page, prefer)
    b = extract_page_text(page, other)
    if count_chars(a) >= ratio * count_chars(b) and count_chars(a) > 0:
        return a, prefer
    if count_chars(b) > 0:
        return b, other
    return "", "none"


_MULTI_BLANK = re.compile(r"\n{3,}")


def clean_text(text: str, squeeze_spaces: bool = False) -> str:
    """
    Normalise extracted text: unify newlines, drop trailing spaces, remove
    leading/trailing blank lines, collapse 3+ blank lines to one blank line.
    `squeeze_spaces=True` also collapses runs of 3+ spaces to 2 (loses alignment).
    """
    text = text.replace("\r\n", "\n").replace("\r", "\n").replace("\x0c", "\n")
    lines = [ln.rstrip() for ln in text.split("\n")]
    if squeeze_spaces:
        lines = [re.sub(r" {3,}", "  ", ln) for ln in lines]
    text = "\n".join(lines).strip("\n")
    return _MULTI_BLANK.sub("\n\n", text)


# --------------------------------------------------------------------------- #
# OCR
# --------------------------------------------------------------------------- #

def ocr_backend() -> str | None:
    """
    Return the OCR backend available on this machine, or None:
      "vision"    — macOS Vision framework via the bundled Swift helper (no install)
      "tesseract" — `tesseract` + `pdftoppm` on PATH
    """
    if platform.system() == "Darwin" and (shutil.which("swiftc") or shutil.which("swift")):
        return "vision"
    if shutil.which("tesseract") and shutil.which("pdftoppm"):
        return "tesseract"
    return None


def _vision_binary() -> list[str]:
    """Compile the Swift OCR helper once into the cache; fall back to the interpreter."""
    src = SCRIPTS_DIR / "ocr_macos.swift"
    if shutil.which("swiftc"):
        CACHE_DIR.mkdir(parents=True, exist_ok=True)
        binary = CACHE_DIR / "ocr_macos"
        if not binary.exists() or binary.stat().st_mtime < src.stat().st_mtime:
            subprocess.run(["swiftc", "-O", str(src), "-o", str(binary)],
                           check=True, capture_output=True, text=True)
        return [str(binary)]
    return ["swift", str(src)]


def _ocr_vision(pdf_path: Path, pages: list[int], languages: str | None) -> dict[int, str]:
    cmd = [*_vision_binary(), str(pdf_path), ",".join(map(str, pages))]
    if languages:
        cmd.append(languages)
    res = subprocess.run(cmd, capture_output=True, text=True, timeout=600)
    if res.returncode != 0:
        raise RuntimeError(f"vision OCR failed: {res.stderr.strip()[:300]}")
    return {int(k): v for k, v in json.loads(res.stdout).items()}


def _ocr_tesseract(pdf_path: Path, pages: list[int], languages: str | None) -> dict[int, str]:
    out: dict[int, str] = {}
    lang = (languages or "eng").replace(",", "+")
    with tempfile.TemporaryDirectory() as tmp:
        for p in pages:
            prefix = Path(tmp) / f"p{p}"
            subprocess.run(["pdftoppm", "-r", "300", "-f", str(p), "-l", str(p), "-png",
                            "-singlefile", str(pdf_path), str(prefix)], check=True,
                           capture_output=True)
            res = subprocess.run(["tesseract", f"{prefix}.png", "-", "-l", lang],
                                 capture_output=True, text=True)
            out[p] = res.stdout
    return out


def ocr_pages(pdf_path: Path, pages: list[int], backend: str | None = None,
              languages: str | None = None) -> dict[int, str]:
    """
    OCR the given 1-based page numbers. Returns {page_number: text}.
    `languages`: comma list, e.g. "en-US,fr-FR,zh-Hans" (Vision) or "eng,fra" (tesseract).
    Raises RuntimeError when no backend is available or OCR fails.
    """
    if not pages:
        return {}
    backend = backend or ocr_backend()
    if backend == "vision":
        return _ocr_vision(Path(pdf_path), pages, languages)
    if backend == "tesseract":
        return _ocr_tesseract(Path(pdf_path), pages, languages)
    raise RuntimeError("no OCR backend (macOS Vision, or tesseract + pdftoppm)")


# --------------------------------------------------------------------------- #
# Rendering
# --------------------------------------------------------------------------- #

@dataclass
class PageResult:
    number: int            # 1-based
    text: str
    method: str            # layout | plain | ocr-vision | ocr-tesseract | none
    notes: list[str] = field(default_factory=list)


def _yaml_value(v) -> str:
    if v is None:
        return '""'
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return str(v)
    s = str(v).replace('"', '\\"')
    return f'"{s}"'


TEMPLATE_SECTIONS = ("document", "page", "empty-page")
_SECTION_MARKER = re.compile(r"^<!-- @([a-z-]+) -->[ \t]*$", re.MULTILINE)
_PLACEHOLDER = re.compile(r"\{\{([A-Z_]+)\}\}")


def load_template(path: Path | str | None = None) -> dict[str, str]:
    """
    Read an output template: `<!-- @name -->` marker lines split it into sections.
    Text before the first marker is ignored. Raises ValueError if a section is missing.
    """
    text = Path(path or DEFAULT_TEMPLATE).read_text(encoding="utf-8")
    parts = _SECTION_MARKER.split(text)
    sections = {parts[i]: parts[i + 1].strip("\n") for i in range(1, len(parts) - 1, 2)}
    missing = [n for n in TEMPLATE_SECTIONS if n not in sections]
    if missing:
        raise ValueError(f"template {path or DEFAULT_TEMPLATE} is missing section(s): {', '.join(missing)}")
    return sections


def fill(template: str, values: dict[str, str]) -> str:
    """Replace {{NAME}} placeholders in one pass (inserted values are never re-scanned).
    Unknown placeholders are left visible."""
    return _PLACEHOLDER.sub(lambda m: values.get(m.group(1), m.group(0)), template)


def render_markdown(source_name: str, meta: dict, pages: list[PageResult], pdf_sha: str,
                    body: str = "fenced", extracted_at: str | None = None,
                    template: dict[str, str] | None = None) -> str:
    """
    Build the full Markdown document: frontmatter (machine contract, built here) + body
    (format owned by the template, see ../references/templates/markdown-output.md).
      body="fenced": each page's text in a ```text block (keeps alignment; safe for tables)
      body="raw":    each page's text as-is (reads as prose; alignment is lost when rendered)
    """
    tpl = template or load_template()
    methods = sorted({p.method for p in pages})
    fm = {
        "source": source_name,
        "source_sha256": pdf_sha,
        "generator": GENERATOR,
        "generator_version": GENERATOR_VERSION,
        "extracted_at": extracted_at or _dt.datetime.now().isoformat(timespec="seconds"),
        "pages": meta.get("pages", len(pages)),
        "methods": ",".join(methods),
        "pdf_title": meta.get("title"),
        "pdf_author": meta.get("author"),
        "pdf_producer": meta.get("producer"),
        "pdf_created": meta.get("created"),
        "encrypted": meta.get("encrypted", False),
    }
    frontmatter = "\n".join(["---", *(f"{k}: {_yaml_value(v)}" for k, v in fm.items()), "---"])

    rendered = []
    for p in pages:
        text = p.text.strip("\n")
        if not text:
            text = tpl["empty-page"]
        elif body == "fenced":
            fence = "````" if "```" in text else "```"
            text = f"{fence}text\n{text}\n{fence}"
        method = p.method + ("; " + "; ".join(p.notes) if p.notes else "")
        rendered.append(fill(tpl["page"], {"PAGE_NUMBER": str(p.number), "METHOD": method, "TEXT": text}))

    title = meta.get("title") or Path(source_name).stem
    doc = fill(tpl["document"], {"TITLE": title, "PAGES": "\n\n".join(rendered)})
    return (frontmatter + "\n\n" + doc).rstrip("\n") + "\n"
