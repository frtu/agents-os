def _pdf_date(value) -> str | None:
    """Convert a PDF date string (D:YYYYMMDDHHmmSS...) to ISO `YYYY-MM-DD`."""
    if not value:
        return None
    m = re.match(r"D?:?(\d{4})(\d{2})?(\d{2})?", str(value))
    if not m:
        return None
    y, mo, d = m.group(1), m.group(2) or "01", m.group(3) or "01"
    return f"{y}-{mo}-{d}"


def pdf_metadata(reader) -> dict:
    """Return {title, author, producer, created, pages, encrypted} from a pypdf reader."""
    info = {}
    try:
        info = reader.metadata or {}
    except Exception:
        pass
    get = lambda k: (str(info.get(k)).strip() if info.get(k) else None)  # noqa: E731
    return {
        "title": get("/Title"),
        "author": get("/Author"),
        "producer": get("/Producer"),
        "created": _pdf_date(info.get("/CreationDate")),
        "pages": len(reader.pages),
        "encrypted": bool(reader.is_encrypted),
    }


